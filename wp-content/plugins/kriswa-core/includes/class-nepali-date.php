	/**
	 * Convert a Gregorian date to BS.
	 *
	 * @param int $timestamp Unix timestamp (interpreted in site timezone date parts by caller).
	 * @param string $ymd    Alternatively, a Y-m-d string.
	 * @return array|null    [year, month(1-12), day] or null if out of range.
	 */
	public static function ad_to_bs( $ymd ) {
		try {
			$epoch = new DateTimeImmutable( self::EPOCH, new DateTimeZone( 'UTC' ) );
			$date  = new DateTimeImmutable( $ymd, new DateTimeZone( 'UTC' ) );
		} catch ( Exception $e ) {
			return null;
		}
		$days = (int) $epoch->diff( $date )->format( '%r%a' );
		if ( $days < 0 ) {
			return null;
		}
		foreach ( self::table() as $year => $months ) {
			$len = array_sum( $months );
			if ( $days >= $len ) {
				$days -= $len;
				continue;
			}
			foreach ( $months as $i => $dim ) {
				if ( $days < $dim ) {
					return array( (int) $year, $i + 1, $days + 1 );
				}
				$days -= $dim;
			}
		}
		return null;
	}

	/**
	 * Convert a BS date to Gregorian Y-m-d.
	 */
	public static function bs_to_ad( $year, $month, $day ) {
		$table = self::table();
		if ( ! isset( $table[ $year ] ) || $month < 1 || $month > 12 || $day < 1 || $day > $table[ $year ][ $month - 1 ] ) {
			return null;
		}
		$days = 0;
		foreach ( $table as $y => $months ) {
			if ( $y < $year ) {
				$days += array_sum( $months );
			}
		}
		for ( $m = 0; $m < $month - 1; $m++ ) {
			$days += $table[ $year ][ $m ];
		}
		$days += $day - 1;
		$d = new DateTimeImmutable( self::EPOCH, new DateTimeZone( 'UTC' ) );
		return $d->modify( '+' . $days . ' days' )->format( 'Y-m-d' );
	}

	/** Replace ASCII digits with Devanagari digits. */
	public static function numerals( $str ) {
		return strtr( (string) $str, array_combine( str_split( '0123456789' ), array( '०', '१', '२', '३', '४', '५', '६', '७', '८', '९' ) ) );
	}

	/**
	 * Format a Gregorian date as a human BS date string.
	 *
	 * @param string $ymd    Gregorian Y-m-d.
	 * @param string $locale 'ne' for Devanagari, anything else for transliterated English.
	 */
	public static function format( $ymd, $locale = 'ne' ) {
		$bs = self::ad_to_bs( $ymd );
		if ( ! $bs ) {
			return '';
		}
		list( $y, $m, $d ) = $bs;
		if ( 'ne' === $locale ) {
			return self::numerals( $d ) . ' ' . self::MONTHS_NE[ $m - 1 ] . ' ' . self::numerals( $y );
		}
		return $d . ' ' . self::MONTHS_EN[ $m - 1 ] . ' ' . $y . ' BS';
	}
